// node env in browser
import compat, {setImmediate, clearImmediate} from 'lif-kernel/compat';
globalThis.global = globalThis;
import buffer from 'buffer';
import img_sizes from './img_sizes.json' with {type: 'json'};
globalThis.Buffer = buffer.Buffer;
process.env.NODE_BACKEND = 'js';
process.on = ()=>{};
process.argv = [''+globalThis.location];
process.exit = code=>console.warn('process.exit('+(code||0)+')');
globalThis.setImmediate = setImmediate;
globalThis.clearImmediate = clearImmediate;
globalThis.__DEV__ = false;
// require() inside ES modules (bundler style, not valid in the browser):
// - modules: registered by web/main.tsx once loaded, by the path used in
//   the require() call
// - images: return a React Native image source {uri, width, height}. The
//   uri is the path from the project root (served by lif.web_exports), using
//   the @2x/@3x file on a high density screen. The sizes come from
//   web/img_sizes.json (generated by web/img_sizes_gen.mjs)
let require_modules = {};
function require_image(path){
  let uri = '/'+path.replace(/^(\.\.?\/)+/, '');
  let size = img_sizes[uri];
  if (!size)
    return {uri};
  let dpr = Math.ceil(globalThis.devicePixelRatio||1);
  let scale = size.scales.findLast(s=>s<=dpr)||1;
  if (scale>1)
    uri = uri.replace(/\.png$/, '@'+scale+'x.png');
  return {uri, width: size.width, height: size.height};
}
globalThis.require = function(path){
  if (path in require_modules)
    return require_modules[path];
  if (typeof path=='string' && path.match(/\.(png|jpg|jpeg|gif|svg)$/))
    return require_image(path);
  console.warn('require() not supported:', path);
  return {};
};
globalThis.require.register = (path, mod)=>{
  require_modules[path] = mod;
};
// enable from URL: ?NODE_ENV=development
// enable from console: localStorage.setItem('NODE_ENV', 'development');
let node_env = new URLSearchParams(location.search).get('NODE_ENV') ||
  localStorage.getItem('NODE_ENV');
if (node_env)
  console.log('NODE_ENV '+node_env);
((globalThis.process ||= {}).env ||= {}).NODE_ENV = node_env||'production';
